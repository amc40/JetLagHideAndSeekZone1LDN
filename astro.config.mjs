const base = "JetLagHideAndSeekZone1LDN";

// The default Workbox globPatterns only picks up common web-asset
// extensions (js/css/html/...), so binary/data files copied into public/
// need to be added explicitly - otherwise they're only cached the first
// time a page fetches them at runtime (via the app's own Cache API calls),
// not precached on install. That's fine for data fetched from Overpass at
// runtime, but anything the app needs to work offline from a cold install
// (no prior visit) has to go in this list - e.g. the arcgis geodesic engine
// WASM (generated by scripts/copy-arcgis-assets.mjs) and the bundled
// elevation grid used offline by the Sea Level Measuring question.
/** @param {string} relativePath */
const hashDataFile = (relativePath) => {
    const absolutePath = fileURLToPath(
        new URL(`./public/${relativePath}`, import.meta.url),
    );
    return existsSync(absolutePath)
        ? createHash("md5").update(readFileSync(absolutePath)).digest("hex")
        : null;
};

/** @param {string} relativePath */
const precacheDataFile = (relativePath) => {
    const revision = hashDataFile(relativePath);
    return revision ? [{ url: relativePath, revision }] : [];
};

// The app also fetches these same files at runtime through its own Cache API
// wrapper (`cacheFetch`, in CacheType.PERMANENT_CACHE), independently of the
// Workbox precache above. That wrapper caches responses keyed only by URL
// with no expiry, so a browser that cached one of these files before a
// content update (e.g. an older curated-stations.geojson missing some
// station icons) keeps serving the stale copy forever - even after the
// service worker itself updates - which is why "clear site data" or
// incognito "fixes" it. Exposing a content hash per file here lets runtime
// fetches append it as a `?v=` query param, so updated content becomes a
// new cache key and is fetched fresh automatically, with no risk to
// localStorage-backed game state (which the Cache API never touches).
const versionedDataFiles = [
    "coastline50.geojson",
    "curated-aquariums.geojson",
    "curated-cinemas.geojson",
    "curated-consulates.geojson",
    "curated-highspeed.geojson",
    "curated-hospitals.geojson",
    "curated-libraries.geojson",
    "curated-museums.geojson",
    "curated-parks.geojson",
    "curated-stations.geojson",
    "london-boroughs.geojson",
    "thames.geojson",
    "elevation-london.bin",
];
const dataFileVersions = Object.fromEntries(
    versionedDataFiles.map((file) => [file, hashDataFile(file) ?? "0"]),
);

const additionalManifestEntries = [
    ...precacheDataFile("arcgis-assets/esri/geometry/support/pe-wasm.wasm"),
    ...precacheDataFile("elevation-london.bin"),
    ...precacheDataFile("coastline50.geojson"),
    ...precacheDataFile("curated-aquariums.geojson"),
    ...precacheDataFile("curated-cinemas.geojson"),
    ...precacheDataFile("curated-consulates.geojson"),
    ...precacheDataFile("curated-highspeed.geojson"),
    ...precacheDataFile("curated-hospitals.geojson"),
    ...precacheDataFile("curated-libraries.geojson"),
    ...precacheDataFile("curated-museums.geojson"),
    ...precacheDataFile("curated-parks.geojson"),
    ...precacheDataFile("curated-stations.geojson"),
    ...precacheDataFile("london-boroughs.geojson"),
    ...precacheDataFile("thames.geojson"),
    // Leaflet marker icons - referenced only via string-built URLs
    // (DraggableMarkers.tsx), so Vite's build never sees an import and the
    // default Workbox globPatterns (js/css/html) never picks up these PNGs.
    // Without this they 404 offline the first time a new question marker
    // (a color the user hasn't dragged yet, so never runtime-cached) is
    // added. Derived from ICON_COLORS so a new color added there is
    // automatically precached too.
    ...Object.keys(ICON_COLORS).flatMap((color) =>
        precacheDataFile(`marker-icon-2x-${color}.png`),
    ),
    ...precacheDataFile("marker-icon-2x.png"),
    ...precacheDataFile("marker-icon.png"),
    ...precacheDataFile("marker-shadow.png"),
];

// Despite the name, this isn't tile-specific - it's a general CacheFirst
// runtime-caching entry for any third-party host whose responses should
// persist for offline use once fetched at least once.
/**
 * @param {RegExp} urlPattern
 * @param {string} cacheName
 */
const tileHostCaching = (urlPattern, cacheName) => ({
    urlPattern,
    handler: /** @type {"CacheFirst"} */ ("CacheFirst"),
    options: {
        cacheName,
        expiration: {
            maxEntries: 2000,
            maxAgeSeconds: 60 * 60 * 24 * 30,
        },
        cacheableResponse: {
            statuses: [0, 200],
        },
    },
});

